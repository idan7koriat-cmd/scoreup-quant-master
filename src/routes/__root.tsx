/** מאתחל את PostHog פעם אחת בצד הלקוח, ושולח $pageview בכל ניווט בין מסכים. */
function PostHogTracker() {
  const href = useRouterState({ select: (s) => s.location.href });

  useEffect(() => {
    initPostHog();
  }, []);

  useEffect(() => {
    if (isPostHogReady()) posthog.capture("$pageview");
  }, [href]);

  return null;
}

